// node character/export-c.js  -> firmware/include/nib_sprites.h
// All characters x all states as RGB565 NxN arrays (0xF81F = transparent key) + lookup table NIB_SET[char][state].
const fs = require("fs"), path = require("path");
const { CHARACTERS, STATES, N } = require("./sprites");
const rgb565 = hex => { const n = parseInt(hex.slice(1), 16); return ((n >> 19 & 31) << 11) | ((n >> 10 & 63) << 5) | (n >> 3 & 31); };
const ids = ["nib", "dragon", "robot", "penguin"];   // device ships 4 characters (saves flash); the simulator still has all 10
let out = `// generated by character/export-c.js — do not edit\n#pragma once\n#include <stdint.h>\n#define NIB_KEY 0xF81F\n#define NIB_W ${N}\n#define NIB_H ${N}\n#define NIB_CHARS ${ids.length}\n#define NIB_STATES ${STATES.length}\n`;
out += `enum NibState { ${STATES.map(s => "ST_" + s.toUpperCase()).join(", ")} };\n`;
for (const id of ids) {
  const ch = CHARACTERS[id];
  for (const s of STATES) {
    const rows = ch.FRAMES[s];
    if (rows.length !== N || rows.some(r => r.length !== N)) throw new Error(`bad frame ${id}/${s}`);
    const px = rows.join("").split("").map(c => c === "." ? 0xF81F : rgb565(ch.PALETTE[c]));
    out += `static const uint16_t SPR_${id.toUpperCase()}_${s.toUpperCase()}[${N * N}] PROGMEM = {${px.map(v => "0x" + v.toString(16).padStart(4, "0")).join(",")}};\n`;
  }
}
out += `static const uint16_t* const NIB_SET[NIB_CHARS][NIB_STATES] = {\n${ids.map(id => "  {" + STATES.map(s => `SPR_${id.toUpperCase()}_${s.toUpperCase()}`).join(",") + "}").join(",\n")}\n};\n`;
out += `static const char* const NIB_NAMES[NIB_CHARS] = {${ids.map(id => JSON.stringify(CHARACTERS[id].name)).join(",")}};\n`;
fs.writeFileSync(path.join(__dirname, "../firmware/include/nib_sprites.h"), out);
console.log(`wrote nib_sprites.h (${ids.length} characters)`);
